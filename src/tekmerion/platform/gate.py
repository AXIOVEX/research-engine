"""The append gate (Spec 005 T507) — the only path by which the E1
platform writes to a study ledger.

`GatedStudyWriter` wraps one study's `StudyStore`. Every method:
1. builds the canonical intent (action, tenant, study, event, payload);
2. asks `PlatformService` to authorize it — session + role + tenant
   binding + MFA + step-up (verdict-class) + enrolled-key signature
   (self-custody) or in-session delegated signing;
3. only then performs the store write, with the authorization's
   attribution embedded in the record.

Attribution rides inside append payloads and claim content under
`attribution` (§4: random actor ID + key fingerprint + custody —
never PII). A freeze's checkpoint payload is generated by Axiomere
itself; there the actor ID on the checkpoint is the attribution, and
the gate's authorization is the platform-side half of the record
(the platform↔study join is completed in E4, CLM-005-22).

Auth modes: `SessionAuth` (human, key-bound) or `ApiKeyAuth`
(service account, scope-bound; CLM-005-18). There is no third mode —
in particular there is no session-only unsigned write path
(DN-011's excluded repeal of Article XIII).
"""

from __future__ import annotations

import json
from dataclasses import dataclass
from typing import Any, Optional

from tekmerion.store import StudyStore

from . import authz
from .service import AppendAuthorization, PlatformService


@dataclass
class SessionAuth:
    session_token: str
    key_fingerprint: str
    signature: Optional[bytes] = None    # required for self-custody; None for delegated


@dataclass
class ApiKeyAuth:
    key_id: str
    secret: str


Auth = SessionAuth | ApiKeyAuth


def canonical_intent(*, action: str, tenant_id: str, study_id: str,
                     event: str, payload: dict) -> bytes:
    """The exact bytes an actor's key signs: canonical JSON over the
    append's identity. Any change to action, tenant, study, event, or
    payload invalidates the signature — that is the point."""
    doc = {
        "action": action, "tenant_id": tenant_id, "study_id": study_id,
        "event": event, "payload": payload,
    }
    return json.dumps(doc, sort_keys=True, separators=(",", ":")).encode("utf-8")


class GatedStudyWriter:
    def __init__(self, platform: PlatformService, store: StudyStore, *,
                 tenant_id: str, study_id: str) -> None:
        self.platform = platform
        self.store = store
        self.tenant_id = tenant_id
        self.study_id = study_id

    # -- core ----------------------------------------------------------------

    def _authorize(self, auth: Auth, action: str, event: str, payload: dict) -> AppendAuthorization:
        if isinstance(auth, SessionAuth):
            intent = canonical_intent(action=action, tenant_id=self.tenant_id,
                                      study_id=self.study_id, event=event, payload=payload)
            return self.platform.authorize_study_append(
                auth.session_token, tenant_id=self.tenant_id, action=action,
                intent=intent, key_fingerprint=auth.key_fingerprint,
                signature=auth.signature)
        return self.platform.authorize_api_append(
            auth.key_id, auth.secret, tenant_id=self.tenant_id, action=action)

    # -- study operations (Spec 002 surface, gated) -----------------------------

    def register_claim(self, auth: Auth, claim_id: str, content: dict[str, Any],
                       *, score: Optional[float] = None) -> dict:
        ctx = self._authorize(auth, authz.REGISTER_CLAIM, "claim.registered", content)
        return self.store.register_claim(
            claim_id, {**content, "attribution": ctx.attribution()},
            actor=ctx.identity.actor_id, score=score)

    def log_query(self, auth: Auth, connector: str, query: dict[str, Any]) -> dict:
        ctx = self._authorize(auth, authz.LOG_QUERY, "connector.query",
                              {"connector": connector, **query})
        return self.store.log_query(connector, {**query, "attribution": ctx.attribution()},
                                    actor=ctx.identity.actor_id)

    def issue_verdict(self, auth: Auth, claim_id: str, verdict: dict[str, Any]) -> dict:
        ctx = self._authorize(auth, authz.ISSUE_VERDICT, "verdict.issued",
                              {"claim_id": claim_id, **verdict})
        return self.store.issue_verdict(
            claim_id, {**verdict, "attribution": ctx.attribution()},
            actor=ctx.identity.actor_id)

    def withdraw_claim(self, auth: Auth, claim_id: str, *, reason: str) -> dict:
        ctx = self._authorize(auth, authz.WITHDRAW_CLAIM, "claim.withdrawn",
                              {"claim_id": claim_id, "reason": reason})
        return self.store.withdraw(claim_id, reason=reason, actor=ctx.identity.actor_id)

    def freeze(self, auth: Auth) -> dict:
        ctx = self._authorize(auth, authz.FREEZE, "study.frozen", {"study_id": self.study_id})
        return self.store.freeze(actor=ctx.identity.actor_id)
